"""Stock options forced onto a weighed Item.

Every option this app applies already exists natively in ERPNext. This module
only lists them in one place so the set is reviewable, and works out whether it
is safe to apply them.

ERPNext reads Item.batch_number_series in Batch.autoname and
Item.serial_no_series when it allocates serials, and both take priority over
the naming series prefix in Stock Settings. So setting them here is all that is
needed - nothing has to be generated by this app.
"""

import frappe
from frappe import _

# Field -> value forced onto a weighed Item.
PLATE_ITEM_DEFAULTS = {
	"stock_uom": "Nos",
	"is_stock_item": 1,
	"is_purchase_item": 1,
	"has_batch_no": 1,
	"create_new_batch": 1,
	"has_serial_no": 1,
	"valuation_method": "FIFO",
}

# has_expiry_date and retain_sample are deliberately absent: steel plate has
# neither an expiry nor a sample to retain, so both keep their ERPNext defaults.

# Item field <- Item Group field it is copied from.
SERIES_FIELDS = {
	"batch_number_series": "custom_batch_number_series",
	"serial_no_series": "custom_serial_no_series",
}

# Tables that mean an Item has already been used.
TRANSACTION_REFERENCES = (
	("Stock Ledger Entry", "item_code"),
	("Purchase Order Item", "item_code"),
	("Purchase Receipt Item", "item_code"),
	("BOM Item", "item_code"),
)

STOCK_UOM_CHANGE_MESSAGE = _(
	"Item {0} already holds stock under stock UOM {1} and cannot be moved to {2}. "
	"Run it down first, or create a new Item."
)

TRACKING_ON_MESSAGE = _(
	"Item {0} already holds stock, so {1} were not changed. Batch and serial "
	"tracking can only be switched on before the first movement."
)


def item_has_stock(item_code) -> bool:
	"""True once a single Stock Ledger Entry exists for this Item.

	Deliberately conservative: a non-zero balance only appears after the first
	movement, so the ledger itself is the safe test.
	"""
	if not item_code:
		return False

	return bool(frappe.db.exists("Stock Ledger Entry", {"item_code": item_code}))


def item_has_transactions(item_code) -> bool:
	"""True when anything at all already refers to this Item.

	The dimension lock uses this: once an Item is in a purchase order, a
	receipt, a bill of materials or the stock ledger, its size must not move,
	because those documents quote the old size.
	"""
	if not item_code:
		return False

	for doctype, field in TRANSACTION_REFERENCES:
		if frappe.db.exists(doctype, {field: item_code}):
			return True

	return False


def apply_plate_item_defaults(doc) -> None:
	"""Force the stock options and the naming series onto a weighed Item.

	Nothing that could reinterpret an existing balance is changed. Turning on
	serial tracking, automatic batches, or moving the stock UOM under stock that
	is already there breaks the ledger, so an Item in that state is reported and
	left as it is.
	"""
	wanted_uom = PLATE_ITEM_DEFAULTS["stock_uom"]
	has_stock = item_has_stock(doc.get("name")) if doc.get("name") else False

	if has_stock and doc.get("stock_uom") not in (None, "", wanted_uom):
		frappe.throw(
			STOCK_UOM_CHANGE_MESSAGE.format(doc.get("name"), doc.get("stock_uom"), wanted_uom),
			title=_("Stock UOM cannot be changed"),
		)

	not_applied = []

	for field, value in PLATE_ITEM_DEFAULTS.items():
		if has_stock and doc.get(field) != value:
			not_applied.append(field)
			continue
		doc.set(field, value)

	doc.set("weight_uom", "Kg")

	if not has_stock:
		copy_series_from_group(doc)

	if not_applied:
		frappe.msgprint(
			TRACKING_ON_MESSAGE.format(doc.get("name"), ", ".join(not_applied)),
			alert=True,
		)


def copy_series_from_group(doc) -> None:
	"""Copy the grade's batch and serial series onto the Item.

	Only filled in when the Item does not already have one, so a series typed
	directly on the Item always wins.
	"""
	item_group = frappe.db.get_value(
		"Item Group",
		doc.get("item_group"),
		list(SERIES_FIELDS.values()),
		as_dict=True,
	)

	if not item_group:
		return

	for field, group_field in SERIES_FIELDS.items():
		if doc.get(field):
			continue
		series = item_group.get(group_field)
		if series:
			doc.set(field, series)
